CREATE OR REPLACE FUNCTION public.mf_post_basic(p_key text, p_date date, p_type text, p_from uuid, p_to uuid, p_amount bigint, p_concept text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
 v_owner uuid := (select auth.uid());
 v_existing public.mf_events%ROWTYPE;
 v_id uuid;
 v_kind text;
 v_balance bigint;
BEGIN
 IF v_owner IS NULL THEN RAISE EXCEPTION 'Autenticaci�n requerida' USING ERRCODE='28000'; END IF;
 IF p_key IS NULL OR length(p_key) NOT BETWEEN 1 AND 180 THEN RAISE EXCEPTION 'Clave de idempotencia inv�lida'; END IF;
 IF p_date IS NULL OR p_date > CURRENT_DATE THEN RAISE EXCEPTION 'Fecha inv�lida o futura'; END IF;
 IF p_type IS NULL OR p_type NOT IN ('income','expense','transfer') THEN RAISE EXCEPTION 'Tipo de movimiento no permitido'; END IF;
 IF p_amount IS NULL OR p_amount <= 0 THEN RAISE EXCEPTION 'Importe inv�lido'; END IF;
 IF p_concept IS NULL OR length(trim(p_concept)) NOT BETWEEN 1 AND 300 THEN RAISE EXCEPTION 'Concepto inv�lido'; END IF;
 IF (p_type='income' AND (p_from IS NOT NULL OR p_to IS NULL))
 OR (p_type='expense' AND (p_from IS NULL OR p_to IS NOT NULL))
 OR (p_type='transfer' AND (p_from IS NULL OR p_to IS NULL OR p_from=p_to)) THEN
  RAISE EXCEPTION 'Cuentas incompatibles con el tipo de movimiento';
 END IF;
 -- Serializa operaciones financieras de este usuario para impedir saldos negativos por carreras.
 PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_owner::text, 817263));
 SELECT * INTO v_existing FROM public.mf_events
 WHERE owner_id=v_owner AND idempotency_key=p_key;
 IF FOUND THEN
  IF v_existing.event_date=p_date AND v_existing.event_type=p_type
   AND v_existing.from_account IS NOT DISTINCT FROM p_from
   AND v_existing.to_account IS NOT DISTINCT FROM p_to
   AND v_existing.amount=p_amount AND v_existing.concept=p_concept
   AND v_existing.source='manual' AND v_existing.due_id IS NULL THEN
   RETURN v_existing.id;
  END IF;
  RAISE EXCEPTION 'Clave de idempotencia reutilizada con datos diferentes';
 END IF;
 -- Esta primera RPC solo admite cuentas de activo, no tarjetas ni pr�stamos.
 IF p_from IS NOT NULL THEN
  SELECT kind INTO v_kind FROM public.mf_accounts
  WHERE id=p_from AND owner_id=v_owner AND active=true;
  IF v_kind IS DISTINCT FROM 'asset' THEN RAISE EXCEPTION 'Cuenta de origen inexistente, inactiva o no es activo'; END IF;
 END IF;
 IF p_to IS NOT NULL THEN
  SELECT kind INTO v_kind FROM public.mf_accounts
  WHERE id=p_to AND owner_id=v_owner AND active=true;
  IF v_kind IS DISTINCT FROM 'asset' THEN RAISE EXCEPTION 'Cuenta de destino inexistente, inactiva o no es activo'; END IF;
 END IF;
 IF p_from IS NOT NULL THEN
  SELECT a.opening
   + COALESCE((SELECT sum(e.amount) FROM public.mf_events e WHERE e.owner_id=v_owner AND e.to_account=a.id),0)
   - COALESCE((SELECT sum(e.amount) FROM public.mf_events e WHERE e.owner_id=v_owner AND e.from_account=a.id),0)
  INTO v_balance FROM public.mf_accounts a WHERE a.id=p_from AND a.owner_id=v_owner;
  IF v_balance < p_amount THEN RAISE EXCEPTION 'Saldo insuficiente'; END IF;
 END IF;
 INSERT INTO public.mf_events(owner_id,idempotency_key,event_date,event_type,from_account,to_account,amount,concept,source)
 VALUES(v_owner,p_key,p_date,p_type,p_from,p_to,p_amount,p_concept,'manual') RETURNING id INTO v_id;
 INSERT INTO public.mf_audit(owner_id,action,entity,entity_id,details)
 VALUES(v_owner,'post_basic','mf_events',v_id,pg_catalog.jsonb_build_object('type',p_type,'key',p_key));
 RETURN v_id;
END;
$function$;
CREATE OR REPLACE FUNCTION public.mf_reject_owner_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
    IF NEW.owner_id IS DISTINCT FROM OLD.owner_id THEN
        RAISE EXCEPTION 'No se permite modificar el propietario de la cuenta';
    END IF;

    IF NEW.opening IS DISTINCT FROM OLD.opening THEN
        RAISE EXCEPTION 'No se permite modificar el saldo inicial de una cuenta existente';
    END IF;

    IF NEW.kind IS DISTINCT FROM OLD.kind THEN
        RAISE EXCEPTION 'No se permite modificar el tipo de una cuenta existente';
    END IF;

    RETURN NEW;
END;
$function$;
